#!/usr/bin/env python3
"""AdSense-readiness guard for the deployed copy of mdm1.org. Source files in the repository are never modified.

Google AdSense rejects sites whose pages are mostly thin, templated, machine-translated or "interactive only".
This repository generates thousands of such pages, so on the *deployed artifact* (default: _site) this script:

1. Adds a static footer with links to Privacy Policy, Terms, Contact, About and Guides to EVERY page,
   so the trust pages are reachable from all pages without JavaScript.
2. Keeps the AdSense loader ONLY on hand-written editorial pages (ADS_ALLOW, guides/*) that have at least
   MIN_AD_WORDS visible words. It is removed (together with any <ins class="adsbygoogle"> slot) from everything
   else: policy pages, machine-translated pages (scripts/build-i18n.js output), game / app / tool pages whose
   main content is an interactive widget, and the pipeline-generated plan pages (pages/<number>.html).
   Widen ADS_ALLOW once the site has been approved.
3. Marks very thin pages (fewer than MIN_INDEX_WORDS words) and, unless --keep-generated-indexed is passed,
   the pipeline-generated plan pages as `noindex,follow` (they stay reachable, they just leave the index).
4. Drops every noindex page from all sitemap*.xml files so crawlers are not pointed at low-value URLs.

Run in CI after the "Flatten languages/" step:   python3 scripts/adsense_guard.py --root _site --write
Without --write it only prints the report (dry run).

Tuning knobs are the constants below. Nothing here touches the <meta name="google-adsense-account"> tag.
"""
from __future__ import annotations

import argparse
import re
import sys
from collections import Counter
from pathlib import Path
from urllib.parse import urlparse

SITE = "https://mdm1.org"
MIN_AD_WORDS = 300        # fewer visible words than this -> no ads
MIN_INDEX_WORDS = 150     # fewer visible words than this -> noindex,follow (unless exempt)

# Pages that must stay indexable and ad-free (trust pages) or stay indexable regardless of length.
POLICY = {"privacy.html", "terms.html", "contact.html"}
ALWAYS_INDEX = POLICY | {"index.html", "pages/about.html", "whitepaper.html", "pages/faq.html", "pages/roadmap.html",
                         "pages/tokenomics.html", "pages/sharia.html", "pages/community.html", "pages/md1usd.html"}
# Interactive / third-party-content areas: the page is a widget, so no ads there.
NO_ADS_PREFIX = ("apps/", "tools/", "mecca/", "mecca3d/", "spatial/", "assistant/", "discover/", "projects/")
NO_ADS_FILES = {"games.html", "fight.html", "chat.html", "hub.html", "md1robot.html",
                "pages/game.html", "pages/quiz.html", "pages/ads.html", "pages/ATM.html", "pages/join.html",
                "pages/ideas.html", "pages/dashboard.html"}
# Hand-written pages that may carry ads. guides/* is added automatically.
ADS_ALLOW = {"pages/about.html", "whitepaper.html", "pages/faq.html", "pages/roadmap.html", "pages/tokenomics.html",
             "pages/sharia.html", "pages/community.html", "pages/md1usd.html", "pages/blog.html", "learn/kids.html",
             "learn/library.html"}
GENERATED_RE = re.compile(r"^pages/(\d+|page-\d+)\.html$")   # produced by build-pages.js (daily LLM plan pages)
I18N_MARKER = "generated by scripts/build-i18n.js"

GUARD_MARK = "mdm1-policy-links"
LABELS = {
    "ar": ("سياسة الخصوصية", "الشروط والأحكام", "اتصل بنا", "من نحن", "الأدلة والمقالات"),
    "en": ("Privacy Policy", "Terms & Conditions", "Contact", "About", "Guides"),
}

RE_SCRIPT = re.compile(r"<script\b.*?</script>", re.S | re.I)
RE_STYLE = re.compile(r"<style\b.*?</style>", re.S | re.I)
RE_NONCONTENT = re.compile(r"<(nav|footer|header|noscript|svg|select|button|audio|video)\b.*?</\1>", re.S | re.I)
RE_TAG = re.compile(r"<[^>]+>")
RE_WORD = re.compile(r"[^\W_]+", re.U)
RE_AD_LOADER = re.compile(r'[ \t]*<script\b[^>]*googlesyndication\.com[^>]*>\s*</script>[ \t]*\n?', re.I)
RE_AD_SLOT = re.compile(r'<ins\b[^>]*\bclass="[^"]*adsbygoogle[^"]*"[^>]*>.*?</ins>', re.S | re.I)
RE_AD_PUSH = re.compile(r'<script\b[^>]*>\s*\(adsbygoogle\s*=\s*window\.adsbygoogle\s*\|\|\s*\[\]\)\.push\(\{[^}]*\}\);?\s*</script>', re.S | re.I)
RE_ROBOTS = re.compile(r'<meta\s+name=["\']robots["\'][^>]*>', re.I)
RE_LANG = re.compile(r'<html[^>]*\blang=["\']([A-Za-z-]+)["\']', re.I)


def visible_words(html: str) -> int:
    body = html
    m = re.search(r"<body\b.*?</body>", html, re.S | re.I)
    if m:
        body = m.group(0)
    for rx in (RE_SCRIPT, RE_STYLE, RE_NONCONTENT):
        body = rx.sub(" ", body)
    return len(RE_WORD.findall(RE_TAG.sub(" ", body)))


def url_for(rel: str) -> str:
    if rel == "index.html":
        return SITE + "/"
    if rel.endswith("/index.html"):
        return f"{SITE}/{rel[:-len('index.html')]}"
    return f"{SITE}/{rel}"


def policy_footer(lang: str) -> str:
    l = LABELS["ar"] if lang.lower().startswith("ar") else LABELS["en"]
    links = [("/privacy.html", l[0]), ("/terms.html", l[1]), ("/contact.html", l[2]),
             ("/pages/about.html", l[3]), ("/guides/", l[4])]
    items = " · ".join(f'<a href="{h}" style="color:inherit;text-decoration:underline">{t}</a>' for h, t in links)
    return (f'<nav class="{GUARD_MARK}" aria-label="Site policies" '
            'style="text-align:center;padding:1.2rem 1rem 5rem;font-size:.9rem;line-height:2;opacity:.9">'
            f"{items}</nav>\n")


def process(path: Path, root: Path, write: bool, stats: Counter, noindex_urls: set[str], noindex_generated: bool) -> None:
    rel = path.relative_to(root).as_posix()
    if rel.startswith(("archive/", "node_modules/", ".git/")):
        return
    html = path.read_text(encoding="utf-8", errors="replace")
    if "</body>" not in html.lower():
        stats["skipped_no_body"] += 1
        return
    words = visible_words(html)
    lang_m = RE_LANG.search(html)
    lang = lang_m.group(1) if lang_m else "ar"
    translated = I18N_MARKER in html
    reason = None
    if rel in POLICY:
        reason = "policy"
    elif translated:
        reason = "machine-translated"
    elif rel in NO_ADS_FILES or rel.startswith(NO_ADS_PREFIX):
        reason = "interactive"
    elif GENERATED_RE.match(rel):
        reason = "generated"
    elif words < MIN_AD_WORDS:
        reason = "thin"
    elif rel not in ADS_ALLOW and not rel.startswith("guides/"):
        reason = "not-allowlisted"
    new = html
    has_ads = "googlesyndication.com" in html or "adsbygoogle" in html
    if reason and has_ads:
        new = RE_AD_PUSH.sub("", RE_AD_SLOT.sub("", RE_AD_LOADER.sub("", new)))
        stats[f"ads_removed:{reason}"] += 1
    elif not reason and has_ads:
        stats["ads_kept"] += 1
    # Only (non-translated) thin pages are noindexed; translated pages keep hreflang indexing but never carry ads.
    thin = words < MIN_INDEX_WORDS and rel not in ALWAYS_INDEX and not rel.endswith("index.html") and not translated
    thin = thin or (noindex_generated and bool(GENERATED_RE.match(rel)))
    if thin and not re.search(r'noindex', new, re.I):
        tag = '<meta name="robots" content="noindex,follow">'
        if RE_ROBOTS.search(new):
            new = RE_ROBOTS.sub(tag, new, count=1)
        else:
            new = re.sub(r"(<head\b[^>]*>)", r"\1\n  " + tag, new, count=1, flags=re.I)
        stats["noindex_added"] += 1
    if re.search(r'<meta\s+name=["\']robots["\'][^>]*noindex', new, re.I):
        noindex_urls.add(url_for(rel))
    if GUARD_MARK not in new:
        new = re.sub(r"</body>", lambda _m: policy_footer(lang) + "</body>", new, count=1, flags=re.I)
        stats["footer_added"] += 1
    stats["pages"] += 1
    if write and new != html:
        path.write_text(new, encoding="utf-8")


def prune_sitemaps(root: Path, noindex_urls: set[str], write: bool, stats: Counter) -> None:
    for sm in sorted(root.glob("sitemap*.xml")):
        text = sm.read_text(encoding="utf-8")
        total = 0
        removed = 0

        def keep(m: re.Match) -> str:
            nonlocal total, removed
            total += 1
            loc = re.search(r"<loc>\s*([^<\s]+)\s*</loc>", m.group(0))
            if loc and loc.group(1) in noindex_urls:
                removed += 1
                return ""
            return m.group(0)

        new = re.sub(r"<url>.*?</url>\s*", keep, text, flags=re.S)
        stats[f"sitemap:{sm.name}"] = removed
        if write and removed:
            sm.write_text(new, encoding="utf-8")
        print(f"  {sm.name}: {total} urls, {removed} removed (noindex)")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default="_site")
    ap.add_argument("--write", action="store_true", help="apply changes (default: dry run)")
    ap.add_argument("--keep-generated-indexed", action="store_true",
                    help="do not noindex the pipeline-generated plan pages (pages/<number>.html)")
    args = ap.parse_args()
    root = Path(args.root).resolve()
    if not root.is_dir():
        print(f"root not found: {root}", file=sys.stderr)
        return 1
    stats: Counter = Counter()
    noindex_urls: set[str] = set()
    for p in sorted(root.rglob("*.html")):
        process(p, root, args.write, stats, noindex_urls, not args.keep_generated_indexed)
    print(f"adsense_guard ({'WRITE' if args.write else 'dry run'}) on {root}")
    for k in sorted(stats):
        if not k.startswith("sitemap:"):
            print(f"  {k}: {stats[k]}")
    prune_sitemaps(root, noindex_urls, args.write, stats)
    print(f"  noindex urls total: {len(noindex_urls)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
