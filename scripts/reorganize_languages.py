#!/usr/bin/env python3
"""ONE-TIME, idempotent tidy-up: move the 50 generated language folders (/af /am ... /zh-tw) into languages/.
Public URLs do NOT change: deploy.yml flattens languages/* back to the site root when it builds the Pages artifact,
and scripts/build-i18n.js is patched to write into languages/. deploy.yml must already contain the flatten step (added by hand first).
Refuses to run if any language folder was not generated by build-i18n.js."""
import json, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
deploy = (ROOT / ".github/workflows/deploy.yml").read_text(encoding="utf-8")
if "_site/languages" not in deploy:
    sys.exit("stop, nothing moved: first add the 'Flatten languages/' step to .github/workflows/deploy.yml by hand "
             "(a workflow's GITHUB_TOKEN is not allowed to edit workflow files), then run this again")
codes = list(json.loads((ROOT / "i18n/site.json").read_text(encoding="utf-8"))["langs"])
foreign = [c for c in codes if (ROOT / c).is_dir() and not (ROOT / c / ".i18n-generated").exists()]
if foreign: sys.exit("refusing: not generated by build-i18n.js: " + ", ".join(foreign))
move = [c for c in codes if (ROOT / c).is_dir()]
(ROOT / "languages").mkdir(exist_ok=True)
for c in move: subprocess.run(["git", "mv", c, "languages/" + c], cwd=ROOT, check=True)
print("moved %d language folders into languages/" % len(move))

def patch(path, pairs):
    t = (ROOT / path).read_text(encoding="utf-8")
    for old, new in pairs:
        if new in t: continue                                   # already applied
        if t.count(old) != 1: sys.exit("patch failed in %s: expected exactly one match for %r, found %d" % (path, old[:70], t.count(old)))
        t = t.replace(old, new)
    (ROOT / path).write_text(t, encoding="utf-8")

patch("scripts/build-i18n.js", [
    ("const MARK = '.i18n-generated';\n",
     "const MARK = '.i18n-generated';\nconst LANG_DIR = 'languages';   // all generated language folders live here; deploy.yml flattens them back to /{lang}/ so public URLs never change\n"),
    ("  const dir = path.join(ROOT, c);\n", "  const dir = path.join(ROOT, LANG_DIR, c);\n"),
    ("function write(rel, content) {\n  const f = path.join(ROOT, rel);\n",
     "function write(rel, content) {\n  const f = path.join(ROOT, rel.includes('/') ? path.join(LANG_DIR, rel) : rel);   // root files (sitemap-i18n.xml) stay at the root\n"),
])
print("patched scripts/build-i18n.js")
